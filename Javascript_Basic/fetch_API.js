//Fetch API คือ เครื่องมือใน JavaScript ที่ใช้สำหรับดึงข้อมูลจากแหล่งอื่นผ่านอินเทอร์เน็ต
//ให้เว็บไซต์ของเราไปขอข้อมูลจากที่อื่น แล้วนำข้อมูลมาแสดงบนหน้าเว็บ
//JSON ย่อมาจากJavaScript Object Notation เป็นรูปแบบที่ใช้จัดเก็บและส่งข้อมูลระหว่างระบบ เช่น เว็บไซต์กับเซิร์ฟเวอร์

fetch('https://api.example.com/data') //สั่งให้ JavaScript ไปขอข้อมูลจาก URL ที่กำหนด
    .then(response => response.json()) 
    //เมื่อได้รับการตอบกลับจากเซิร์ฟเวอร์ ให้นำข้อมูลมาแปลงเป็น JSON เพื่อให้ JavaScript ใช้งานได้

    .then(data => console.log(data))
    //เมื่อแปลงข้อมูลเรียบร้อยแล้ว ให้นำข้อมูลมาเก็บในตัวแปร data และแสดงผลใน Console

    .catch(error => console.error('Error:', error));
    //ถ้าเกิดข้อผิดพลาดระหว่างการส่งคำขอหรืออ่านข้อมูล ให้แสดงข้อความ Error ใน Console

//fetch()ขอข้อมูลจาก API, .then()ทำงานต่อเมื่อขั้นตอนก่อนหน้าสำเร็จ, responseข้อมูลตอบกลับจากเซิร์ฟเวอร์
//.catch()จัดการข้อผิดพลาด, console.error()แสดงข้อผิดพลาดใน Console

