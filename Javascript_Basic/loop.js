//ทำงานเหมือนกัน แต่เขียนต่างกัน
//for loop เหมาะกับกรณีที่รู้ว่าจะวนซ้ำกี่รอบ
for (let i = 0; i < 5; i++) { //i++ เพิ่มค่า i ทีละ 1 หลังทำงานในรอบนั้นเสร็จ
    console.log(i);
}

//while loop    เหมาะกับกรณีที่ต้องวนซ้ำไปเรื่อย ๆ จนกว่าเงื่อนไขจะไม่เป็นจริง
let count = 0;
while (count < 5) {
    console.log(count);
    count++; //เพิ่มค่า count ทีละ 1 หลังทำงานในรอบนั้นเสร็จ
}

