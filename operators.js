let a = 10;
let b = 20;

let c = a + b; // การบวกเลข

let isEqual = (a === b); // การเปรียบเทียบค่า ===

let isBothTrue = (a < b && b > 10); //การตรวจสอบหลายเงื่อนไข เครื่องหมาย && (AND)หรือและ
                                    //AND  เป็นจริงต่อเมื่อเงื่อนไขทั้งสองเป็นจริง

let result = (a + b) * 2; //การคำนวณทางคณิตศาสตร์ การบวก การลบ การคูณ

console.log(c);
console.log(isEqual);
console.log(isBothTrue);
console.log(result);