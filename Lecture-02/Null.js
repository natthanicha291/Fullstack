function getVowels(str) {
    const m = str.match(/[aeiou]/gi); 
    //str = ข้อความที่รับเข้ามา .match() = ค้นหาข้อความที่ตรงกับรูปแบบที่กำหนด
    //[aeiou] = ค้นหาตัวอักษร a, e, i, o, u
    //gi = g = ค้นหาทุกตัวอักษรที่ตรงกับรูปแบบ, i = ไม่สนใจตัวพิมพ์ใหญ่/เล็ก
    //m = ตัวแปรที่เก็บผลลัพธ์ของการค้นหา

    if (m === null) {
        return 0;   //ถ้าค้นหาแล้วไม่พบสระเลย ให้คืนค่าเป็น 0
    }
    return m.length; //m = ข้อมูลสระที่ค้นพบ .length = นับจำนวนสมาชิกในข้อมูล
}

