//switch case คำสั่งที่ใช้ตรวจสอบว่าค่าที่เรามีตรงกับตัวเลือกไหนแล้วทำตามตัวเลือกนั้น
//switch...case เหมาะกับการตรวจสอบค่าที่ตรงกับตัวเลือก
//ตัวอย่างเช่น ตรวจสอบหมายเลขเมนู
const status = 700;

switch (status) {
    case 200:
        console.log("OK");
        break; //ใช้หยุดการทำงานของ switch แล้วออกจากบล็อกนั้น
    case 400: //case 400 และ case 500 จะทำงานเหมือนกัน
    case 500:
        console.log("Error");
        break;
    default: //default เปรียบเสมือนทางเลือกสุดท้าย
        console.log("Unknown status");
}
//ถ้าไม่มี break โปรแกรมอาจทำงานต่อไปยังคำสั่งใน case ถัด ๆ ไปได้
//แม้ว่าค่านั้นจะไม่ตรงกับ case ถัดไปก็ตาม พฤติกรรมนี้เรียกว่า fall-through