//การคำนวณทางคณิตศาสตร์
let num1 = 100;

console.log("******Basic Math******");
console.log(num1 + 25);
console.log(num1 - 100);
console.log(num1 * 100);
console.log(num1 / 1500);

console.log("******Additional Mathematical Operations******");
console.log(num1 % 1500); //หารเอาเศษ
console.log(++num1); //เพิ่มค่า num1 ขึ้น 1 ก่อนนำไปแสดงผล
console.log(--num1); //ลดค่า num1 ลง 1 ก่อนนำไปแสดงผล

console.log("******Using the Math Object******");
console.log(Math.PI); //ค่าพายของ π
console.log(Math.sqrt(num1)); //ค่ารากที่สองของ num1